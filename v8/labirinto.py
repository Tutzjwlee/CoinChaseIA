def _conexo(grade):
    """True se todas as casas livres se alcançam."""
    livres = np.argwhere(grade == 0)
    if len(livres) == 0:
        return False
    vistos = {tuple(livres[0])}
    fila = [tuple(livres[0])]
    while fila:
        x, y = fila.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if grade[n] == 0 and n not in vistos:
                vistos.add(n)
                fila.append(n)
    return len(vistos) == len(livres)


def variacao_aleatoria(grade, semente, mudancas=40):
    """Abre e fecha blocos 2x2 do mapa grande (que é feito de blocos 2x2 a partir
    da casa 1), mantendo a borda e a conectividade. Mesma semente = mesmo mapa."""
    rng = np.random.default_rng(semente)
    g = grade.copy()
    blocos = (len(g) - 2) // 2
    posicoes = [(1 + 2 * a, 1 + 2 * b) for a in range(blocos) for b in range(blocos)]
    rng.shuffle(posicoes)
    abertos = fechados = 0
    for (i, j) in posicoes:
        bloco = g[i:i + 2, j:j + 2]
        if abertos < mudancas and (bloco == 1).all():
            g[i:i + 2, j:j + 2] = 0
            if _conexo(g):          # não pode virar uma sala isolada
                abertos += 1
            else:
                g[i:i + 2, j:j + 2] = 1
        elif fechados < mudancas and (bloco == 0).all():
            g[i:i + 2, j:j + 2] = 1
            if _conexo(g):          # não pode cortar o mapa em partes
                fechados += 1
            else:
                g[i:i + 2, j:j + 2] = 0
        if abertos >= mudancas and fechados >= mudancas:
            break
    return g


MAPAS = {
    "original": MAZE_ORIGINAL,
    "grande": MAZE_GRANDE,
    "grande_espelho": np.fliplr(MAZE_GRANDE).copy(),   # espelhado esquerda/direita
    "grande_vertical": np.flipud(MAZE_GRANDE).copy(),  # de cabeça para baixo
    "grande_girado": np.rot90(MAZE_GRANDE).copy(),     # girado 90 graus
    "grande_aleatorio": variacao_aleatoria(MAZE_GRANDE, SEMENTE),  # muda com SEMENTE
}
if MAPA not in MAPAS:
    raise ValueError(f"MAPA={MAPA!r} invalido. Use: {', '.join(MAPAS)}")
MAZE = MAPAS[MAPA]

ACTIONS = {
    0: (-1, 0),  # cima
    1: (1, 0),   # baixo
    2: (0, -1),  # esquerda
    3: (0, 1)    # direita
}

class Labirinto:
    def __init__(self, grade=MAZE):
        self.grade = grade
        self.tamanho = len(grade)
        self.livres = [(i, j) for i in range(self.tamanho) for j in range(self.tamanho) if grade[i][j] == 0]

    def eh_parede(self, x, y):
        if x < 0 or y < 0 or x >= self.tamanho or y >= self.tamanho:
            return True
        return self.grade[x][y] == 1

    def posicao_vazia(self):
        return list(random.choice(self.livres))

    def direcoes_validas(self, pos):
        x, y = pos
        return [a for a in ACTIONS if not self.eh_parede(x + ACTIONS[a][0], y + ACTIONS[a][1])]

    def direcao_aleatoria(self, pos):
        opcoes = self.direcoes_validas(pos)
        return random.choice(opcoes) if opcoes else -1